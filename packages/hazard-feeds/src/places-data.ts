/**
 * Place names for the 3D Globe: countries and larger cities, as plain data.
 *
 * Source: Natural Earth (naturalearthdata.com), public domain. Country label points
 * come from the 1:110m admin-0 countries file; cities are every national capital plus
 * every city of about one million people or more from the 1:50m populated-places
 * file. Scientific stations and historic places are left out. Generated once and
 * checked in, so the Globe never downloads a list at run time.
 *
 * A country is `[ISO 3166-1 alpha-2 code, longitude, latitude, tier]`. Its name is
 * not stored: the label layer asks the browser for it in the person's language
 * (`Intl.DisplayNames`), so one code gives "Nigeria", "Nigéria" or "نيجيريا".
 * A city is `[English name, longitude, latitude, tier]`.
 *
 * `tier` decides how far away a name can be read: 0 is shown from the furthest,
 * 2 only when close (see `places.ts`).
 */


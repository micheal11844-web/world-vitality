/**
 * What people type, per topic and language, for the help chat's matcher.
 *
 * Written in plain lowercase with no accents: the matcher reads both what a
 * person types and these words through the same `normalise()`, so accents,
 * capitals, Arabic vowel marks and apostrophes never matter. A word matches at
 * the START of a word ("subscrib" finds "subscribing", "plan" finds "plans";
 * "plan" is not found inside "airplane"), except Arabic, which glues
 * prefixes onto words and so matches anywhere. Longer phrases count for more (see `scoreTopics`), so "email you"
 * beats the bare "email".
 *
 * English is always tried as well as the reader's own language: people
 * type English into every language of an app.
 */

